def add_week(doc: Document, w: dict) -> None:
    p = doc.add_paragraph()
    p.add_run(f"{w['range']}                                        {w['no']}")
    doc.add_paragraph("毕业设计进展情况")
    t = doc.add_table(rows=1, cols=1)
    t.rows[0].cells[0].text = f"本周：{w['progress']}"
    doc.add_paragraph("导师指导意见")
    t = doc.add_table(rows=1, cols=1)
    t.rows[0].cells[0].text = w["advisor"]
    doc.add_paragraph("存在问题及困难")
    t = doc.add_table(rows=1, cols=1)
    t.rows[0].cells[0].text = w["problem"]
    doc.add_paragraph("解决问题的途径")
    t = doc.add_table(rows=1, cols=1)
    t.rows[0].cells[0].text = w["solution"]
    doc.add_paragraph("")


